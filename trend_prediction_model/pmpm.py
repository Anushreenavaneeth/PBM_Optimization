"""
Cost-Per-Member-Per-Month (PMPM) Tracking
------------------------------------------------

WHAT THIS DOES
--------------
1. Calculates historical PMPM for every drug/year.
2. Calculates predicted 2024 PMPM from the trend prediction model.
3. Performs plausibility checks on predicted beneficiaries and PMPM.
4. Validates predicted 2024 PMPM against actual 2024 CMS data
   when actual 2024 data is available.
5. Calculates MAE, RMSE and MAPE for PMPM predictions.
6. Produces PMPM trend charts.
7. Produces an Actual vs Predicted PMPM validation chart.

PMPM FORMULA
------------
PMPM = Total Drug Cost / Total Beneficiaries / 12

INPUTS
------
1. cms_final.csv
   Historical CMS Part D drug-level data.

2. trend_prediction_handoff.csv
   Predictions generated by the Drug Utilization Trend Prediction model.

OUTPUTS
-------
1. pmpm_tracking.csv
   Historical + predicted PMPM tracking data.

2. pmpm_validation_2024.csv
   Actual vs predicted 2024 PMPM for validation.

3. pmpm_trend_top_drugs.png
   Top PMPM drugs based on 2023 actual PMPM.

4. pmpm_trend_top_drugs_reliable_only.png
   Top PMPM drugs with plausible 2024 predictions.

5. pmpm_actual_vs_predicted_2024.png
   Actual vs predicted 2024 PMPM validation plot.
"""

import os
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

# ============================================================
# CONFIGURATION
# ============================================================

HISTORICAL_PATH = "processed_data/cms_final.csv"
PREDICTED_PATH = "team_handoff/trend_prediction_handoff.csv"
OUTPUT_DIR = "pmpm_output"

OUTPUT_PATH = os.path.join(OUTPUT_DIR, "pmpm_tracking.csv")
VALIDATION_OUTPUT_PATH = os.path.join(OUTPUT_DIR, "pmpm_validation_2024.csv")
CHART_PATH = os.path.join(OUTPUT_DIR, "pmpm_trend_top_drugs.png")
RELIABLE_CHART_PATH = os.path.join(OUTPUT_DIR, "pmpm_trend_top_drugs_reliable_only.png")
VALIDATION_CHART_PATH = os.path.join(OUTPUT_DIR, "pmpm_actual_vs_predicted_2024.png")

TOP_N_FOR_CHART = 8
REFERENCE_YEAR = 2023
PREDICTION_YEAR = 2024


# ============================================================
# PMPM CALCULATION
# ============================================================

def calculate_pmpm(cost: pd.Series, beneficiaries: pd.Series) -> pd.Series:
    """PMPM = Total Drug Cost / Total Beneficiaries / 12 months."""
    return cost / beneficiaries / 12


# ============================================================
# METRIC FUNCTIONS
# ============================================================

def calculate_mae(actual, predicted):
    """Mean Absolute Error."""
    return np.mean(np.abs(actual - predicted))


def calculate_rmse(actual, predicted):
    """Root Mean Squared Error."""
    return np.sqrt(np.mean((actual - predicted) ** 2))


def calculate_mape(actual, predicted):
    """
    Mean Absolute Percentage Error.

    Actual values equal to zero are excluded because
    percentage error is undefined for zero.
    """
    actual = np.asarray(actual)
    predicted = np.asarray(predicted)
    mask = actual != 0

    if mask.sum() == 0:
        return np.nan

    return np.mean(np.abs((actual[mask] - predicted[mask]) / actual[mask])) * 100


# ============================================================
# MAIN
# ============================================================

def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    # ========================================================
    # 1. LOAD HISTORICAL DATA
    # ========================================================

    print("=" * 70)
    print("PMPM TRACKING")
    print("=" * 70)

    print("\nLoading historical data from:")
    print(HISTORICAL_PATH)

    hist = pd.read_csv(HISTORICAL_PATH)
    hist["year"] = pd.to_numeric(hist["year"], errors="coerce")

    print(f"Loaded {hist.shape[0]:,} rows ({hist['Gnrc_Name'].nunique():,} drugs)")
    print(f"Years available: {sorted(hist['year'].dropna().unique())}")

    # ========================================================
    # 2. CALCULATE HISTORICAL PMPM
    # ========================================================

    print("\nCalculating historical PMPM...")

    # Avoid division by zero
    valid_hist = hist["Tot_Benes"] > 0
    hist["PMPM"] = np.nan
    hist.loc[valid_hist, "PMPM"] = calculate_pmpm(
        hist.loc[valid_hist, "Tot_Drug_Cst"], hist.loc[valid_hist, "Tot_Benes"]
    )
    hist["source"] = "actual"

    historical_output = hist[
        ["Gnrc_Name", "Brnd_Name", "year", "Tot_Drug_Cst", "Tot_Benes", "PMPM", "source"]
    ].copy()

    # ========================================================
    # 3. LOAD MODEL PREDICTIONS
    # ========================================================

    print("\nLoading predicted data from:")
    print(PREDICTED_PATH)

    pred = pd.read_csv(PREDICTED_PATH)
    print(f"Loaded {pred.shape[0]:,} predicted drug rows")

    # ========================================================
    # 4. CREATE PREDICTED 2024 DATA
    # ========================================================

    print("\nPreparing predicted 2024 PMPM...")

    pred_output = pd.DataFrame({
        "Gnrc_Name": pred["Gnrc_Name"],
        "Brnd_Name": pred["Brnd_Name"],
        "year": PREDICTION_YEAR,
        "Tot_Drug_Cst": pred["Predicted_2024_Cost"],
        "Tot_Benes": pred["Predicted_2024_Benes"]
    })

    # ========================================================
    # 5. USE 2023 AS THE EXPLICIT REFERENCE YEAR
    # ========================================================

    print(f"\nUsing {REFERENCE_YEAR} as the reference year for prediction plausibility checks.")

    reference_actual_benes = (
        hist[hist["year"] == REFERENCE_YEAR].set_index("Gnrc_Name")["Tot_Benes"]
    )
    pred_output["Reference_2023_Benes"] = pred_output["Gnrc_Name"].map(reference_actual_benes)

    # ========================================================
    # 6. BENEFICIARY PLAUSIBILITY CHECK
    # ========================================================

    """
    Predicted beneficiaries should not suddenly collapse
    or explode compared with the latest actual year.

    Lower bound: predicted >= 30% of 2023 actual
    Upper bound: predicted <= 300% of 2023 actual
    """

    RELIABILITY_LOWER_RATIO = 0.30
    RELIABILITY_UPPER_RATIO = 3.00

    pred_output["Beneficiary_Ratio"] = (
        pred_output["Tot_Benes"] / pred_output["Reference_2023_Benes"]
    )

    beneficiary_plausible = (
        (pred_output["Tot_Benes"] > 0)
        & (pred_output["Tot_Benes"] >= pred_output["Reference_2023_Benes"] * RELIABILITY_LOWER_RATIO)
        & (pred_output["Tot_Benes"] <= pred_output["Reference_2023_Benes"] * RELIABILITY_UPPER_RATIO)
    )

    # ========================================================
    # 7. POSITIVE COST CHECK
    # ========================================================

    cost_plausible = pred_output["Tot_Drug_Cst"] > 0

    # ========================================================
    # 8. INITIAL PLAUSIBILITY FLAG
    # ========================================================

    pred_output["Plausible_Prediction"] = beneficiary_plausible & cost_plausible

    # ========================================================
    # 9. CALCULATE PREDICTED PMPM
    # ========================================================

    pred_output["PMPM"] = np.nan
    plausible_mask = pred_output["Plausible_Prediction"]

    pred_output.loc[plausible_mask, "PMPM"] = calculate_pmpm(
        pred_output.loc[plausible_mask, "Tot_Drug_Cst"],
        pred_output.loc[plausible_mask, "Tot_Benes"]
    )

    # ========================================================
    # 10. PMPM PLAUSIBILITY CHECK AGAINST 2023
    # ========================================================

    reference_2023_pmpm = (
        hist[hist["year"] == REFERENCE_YEAR][["Gnrc_Name", "PMPM"]]
        .rename(columns={"PMPM": "PMPM_2023"})
    )

    pred_output = pred_output.merge(reference_2023_pmpm, on="Gnrc_Name", how="left")

    """
    Second sanity check:
    Predicted PMPM should normally remain within 0.3x to 3x of previous year's PMPM.
    """

    pmpm_ratio = pred_output["PMPM"] / pred_output["PMPM_2023"]
    pred_output["PMPM_Ratio_2024_vs_2023"] = pmpm_ratio

    pmpm_plausible = (
        (pred_output["PMPM"] > 0)
        & (pred_output["PMPM_2023"] > 0)
        & (pmpm_ratio >= 0.30)
        & (pmpm_ratio <= 3.00)
    )

    # Combine both plausibility checks
    pred_output["Plausible_Prediction"] = pred_output["Plausible_Prediction"] & pmpm_plausible

    # Remove PMPM for implausible predictions
    pred_output.loc[~pred_output["Plausible_Prediction"], "PMPM"] = np.nan

    # ========================================================
    # 11. SUMMARY OF PLAUSIBILITY CHECK
    # ========================================================

    total_predictions = len(pred_output)
    plausible_predictions = pred_output["Plausible_Prediction"].sum()
    implausible_predictions = total_predictions - plausible_predictions

    print("\nPrediction plausibility summary:")
    print(f"  Total predictions       : {total_predictions:,}")
    print(f"  Plausible predictions   : {plausible_predictions:,}")
    print(f"  Implausible predictions : {implausible_predictions:,}")
    print(f"  Plausibility rate       : {plausible_predictions / total_predictions * 100:.2f}%")

    # ========================================================
    # 12. ADD SOURCE COLUMN
    # ========================================================

    pred_output["source"] = "predicted"

    # ========================================================
    # 13. COMBINE HISTORICAL + PREDICTED
    # ========================================================

    combined = pd.concat([historical_output, pred_output], ignore_index=True)
    combined = combined.sort_values(["Gnrc_Name", "year", "source"])

    # ========================================================
    # 14. SAVE MAIN PMPM TRACKING FILE
    # ========================================================

    combined.to_csv(OUTPUT_PATH, index=False)

    print("\nSaved PMPM tracking file:")
    print(OUTPUT_PATH)
    print(f"Shape: {combined.shape[0]:,} rows x {combined.shape[1]} columns")

    # ========================================================
    # 15. TOP 10 DRUGS BY 2023 ACTUAL PMPM
    # ========================================================

    latest_actual = combined[
        (combined["year"] == REFERENCE_YEAR) & (combined["source"] == "actual")
    ].copy()

    top_pmpm = (
        latest_actual.dropna(subset=["PMPM"])
        .sort_values("PMPM", ascending=False)
        .head(10)
    )

    print(f"\nTop 10 drugs by {REFERENCE_YEAR} PMPM:")
    print(top_pmpm[["Gnrc_Name", "PMPM"]].to_string(index=False))

    # ========================================================
    # 16. FIRST CHART
    # ========================================================

    top_drugs = top_pmpm.head(TOP_N_FOR_CHART)["Gnrc_Name"].tolist()

    plt.figure(figsize=(10, 6))

    for drug in top_drugs:
        drug_data = combined[
            (combined["Gnrc_Name"] == drug) & (combined["source"] == "actual")
        ].sort_values("year")

        plt.plot(drug_data["year"], drug_data["PMPM"], marker="o", label=drug)

        pred_point = combined[
            (combined["Gnrc_Name"] == drug)
            & (combined["source"] == "predicted")
            & (combined["Plausible_Prediction"] == True)
        ].dropna(subset=["PMPM"])

        if not pred_point.empty:
            plt.scatter(
                pred_point["year"],
                pred_point["PMPM"],
                marker="*",
                s=200,
                zorder=5,
                edgecolor="black"
            )

    plt.xlabel("Year")
    plt.ylabel("PMPM ($)")
    plt.title(
        f"Cost-Per-Member-Per-Month Trend — Top {TOP_N_FOR_CHART} Drugs\n(★ = predicted 2024)"
    )
    plt.legend(bbox_to_anchor=(1.02, 1), loc="upper left", fontsize=8)
    plt.tight_layout()
    plt.savefig(CHART_PATH, dpi=150)
    plt.close()

    print("\nSaved chart:")
    print(CHART_PATH)

    # ========================================================
    # 17. SECOND CHART — PLAUSIBLE PREDICTIONS ONLY
    # ========================================================

    plausible_drug_names = combined[
        (combined["source"] == "predicted")
        & (combined["Plausible_Prediction"] == True)
        & (combined["PMPM"].notna())
    ]["Gnrc_Name"].unique()

    reference_plausible = latest_actual[
        latest_actual["Gnrc_Name"].isin(plausible_drug_names)
    ].copy()

    top_plausible = reference_plausible.sort_values("PMPM", ascending=False).head(TOP_N_FOR_CHART)

    print(f"\nTop {TOP_N_FOR_CHART} drugs by {REFERENCE_YEAR} PMPM with plausible 2024 predictions:")
    print(top_plausible[["Gnrc_Name", "PMPM"]].to_string(index=False))

    top_plausible_drugs = top_plausible["Gnrc_Name"].tolist()

    plt.figure(figsize=(10, 6))

    for drug in top_plausible_drugs:
        drug_data = combined[
            (combined["Gnrc_Name"] == drug) & (combined["source"] == "actual")
        ].sort_values("year")

        plt.plot(drug_data["year"], drug_data["PMPM"], marker="o", label=drug)

        pred_point = combined[
            (combined["Gnrc_Name"] == drug)
            & (combined["source"] == "predicted")
            & (combined["Plausible_Prediction"] == True)
        ].dropna(subset=["PMPM"])

        if not pred_point.empty:
            plt.scatter(
                pred_point["year"],
                pred_point["PMPM"],
                marker="*",
                s=200,
                zorder=5,
                edgecolor="black"
            )

    plt.xlabel("Year")
    plt.ylabel("PMPM ($)")
    plt.title(
        f"PMPM Trend — Top {TOP_N_FOR_CHART} High-PMPM Drugs\n"
        f"(★ = predicted 2024, plausible predictions only)"
    )
    plt.legend(bbox_to_anchor=(1.02, 1), loc="upper left", fontsize=8)
    plt.tight_layout()
    plt.savefig(RELIABLE_CHART_PATH, dpi=150)
    plt.close()

    print("\nSaved plausible-predictions chart:")
    print(RELIABLE_CHART_PATH)

    # ========================================================
    # 18. VALIDATE AGAINST ACTUAL 2024 DATA
    # ========================================================

    print("\n" + "=" * 70)
    print("2024 PMPM VALIDATION")
    print("=" * 70)

    actual_2024 = hist[hist["year"] == PREDICTION_YEAR].copy()

    if actual_2024.empty:
        print("\nNo actual 2024 CMS data was found in the historical dataset.")
        print("Skipping actual-vs-predicted validation.")
        return

    print(f"\nActual 2024 data found: {len(actual_2024):,} drugs")

    # ========================================================
    # 19. PREPARE ACTUAL 2024 PMPM
    # ========================================================

    actual_2024_validation = actual_2024[
        ["Gnrc_Name", "Tot_Drug_Cst", "Tot_Benes", "PMPM"]
    ].copy()

    actual_2024_validation = actual_2024_validation.rename(
        columns={
            "Tot_Drug_Cst": "Actual_2024_Cost",
            "Tot_Benes": "Actual_2024_Benes",
            "PMPM": "Actual_2024_PMPM"
        }
    )

    # ========================================================
    # 20. PREPARE PREDICTED 2024 PMPM
    # ========================================================

    predicted_2024_validation = pred_output[
        ["Gnrc_Name", "Tot_Drug_Cst", "Tot_Benes", "PMPM", "Plausible_Prediction"]
    ].copy()

    predicted_2024_validation = predicted_2024_validation.rename(
        columns={
            "Tot_Drug_Cst": "Predicted_2024_Cost",
            "Tot_Benes": "Predicted_2024_Benes",
            "PMPM": "Predicted_2024_PMPM"
        }
    )

    # ========================================================
    # 21. MERGE ACTUAL + PREDICTED
    # ========================================================

    validation = actual_2024_validation.merge(
        predicted_2024_validation, on="Gnrc_Name", how="inner"
    )

    # Only use predictions that passed plausibility checks
    validation = validation[validation["Plausible_Prediction"] == True].copy()

    # Remove missing PMPM values
    validation = validation.dropna(subset=["Actual_2024_PMPM", "Predicted_2024_PMPM"])

    print(f"\nDrugs available for PMPM validation: {len(validation):,}")

    # ========================================================
    # 22. CALCULATE VALIDATION METRICS
    # ========================================================

    if len(validation) > 0:
        actual_values = validation["Actual_2024_PMPM"].values
        predicted_values = validation["Predicted_2024_PMPM"].values

        mae = calculate_mae(actual_values, predicted_values)
        rmse = calculate_rmse(actual_values, predicted_values)
        mape = calculate_mape(actual_values, predicted_values)

        # R-squared
        ss_res = np.sum((actual_values - predicted_values) ** 2)
        ss_tot = np.sum((actual_values - np.mean(actual_values)) ** 2)

        r2 = 1 - (ss_res / ss_tot) if ss_tot != 0 else np.nan

        print("\n2024 PMPM validation results:")
        print(f"  MAE  : ${mae:,.2f}")
        print(f"  RMSE : ${rmse:,.2f}")
        print(f"  MAPE : {mape:.2f}%")
        print(f"  R²   : {r2:.4f}")

        # ====================================================
        # 23. ADD ERROR COLUMNS
        # ====================================================

        validation["Absolute_Error"] = np.abs(
            validation["Actual_2024_PMPM"] - validation["Predicted_2024_PMPM"]
        )

        validation["Percentage_Error"] = (
            np.abs(
                (validation["Actual_2024_PMPM"] - validation["Predicted_2024_PMPM"])
                / validation["Actual_2024_PMPM"]
            )
            * 100
        )

        # ====================================================
        # 24. SAVE VALIDATION CSV
        # ====================================================

        validation.to_csv(VALIDATION_OUTPUT_PATH, index=False)

        print("\nSaved 2024 PMPM validation:")
        print(VALIDATION_OUTPUT_PATH)

        # ====================================================
        # 25. ACTUAL VS PREDICTED SCATTER PLOT
        # ====================================================

        plt.figure(figsize=(8, 7))

        plt.scatter(
            validation["Actual_2024_PMPM"],
            validation["Predicted_2024_PMPM"],
            alpha=0.6
        )

        # Perfect prediction line
        min_value = min(
            validation["Actual_2024_PMPM"].min(),
            validation["Predicted_2024_PMPM"].min()
        )
        max_value = max(
            validation["Actual_2024_PMPM"].max(),
            validation["Predicted_2024_PMPM"].max()
        )

        plt.plot([min_value, max_value], [min_value, max_value], linestyle="--")

        plt.xlabel("Actual 2024 PMPM ($)")
        plt.ylabel("Predicted 2024 PMPM ($)")
        plt.title("Actual vs Predicted 2024 PMPM")

        plt.tight_layout()
        plt.savefig(VALIDATION_CHART_PATH, dpi=150)
        plt.close()

        print("\nSaved validation chart:")
        print(VALIDATION_CHART_PATH)

    else:
        print("\nNo valid rows were available for PMPM validation.")

    # ========================================================
    # 26. FINAL SUMMARY
    # ========================================================

    print("\n" + "=" * 70)
    print("PMPM PROCESS COMPLETE")
    print("=" * 70)

    print("\nOutputs:")
    print(f"1. PMPM tracking:\n   {OUTPUT_PATH}")
    print(f"\n2. Top PMPM trend:\n   {CHART_PATH}")
    print(f"\n3. Plausible-prediction trend:\n   {RELIABLE_CHART_PATH}")

    if not actual_2024.empty:
        print(f"\n4. Actual vs predicted validation:\n   {VALIDATION_OUTPUT_PATH}")
        print(f"\n5. Validation chart:\n   {VALIDATION_CHART_PATH}")

    print("\nDone.")


# ============================================================
# RUN
# ============================================================

if __name__ == "__main__":
    main()